"""Extract every item's prototype `minecraft:tool` component from the datagen
item component reports into `crates/rewo-data/src/item_tools.rs` (M217,
survival block breaking).

`reports/minecraft/components/item/<name>.json` holds each item's default
components; `minecraft:tool` is

    {"rules": [{"blocks": "#tag" | "id" | ["id", ...], "speed"?: f, "correct_for_drops"?: b}],
     "default_mining_speed"?: f (default 1.0), "damage_per_block"?: i}

`Tool.getMiningSpeed` takes the first rule WITH a speed whose blocks match
(else the default) and `Tool.isCorrectForDrops` the first rule WITH the flag
whose blocks match (else false), so rule order is kept. A list of ids is
written `|`-joined. Re-run after a version bump.
"""
import json
import os

VERSION = os.environ.get("REWO_VERSION", "26.2")
DIR = os.path.join(
    os.environ["APPDATA"], "EwoClient", "rewo", VERSION,
    "datagen", "generated", "reports", "minecraft", "components", "item",
)


def main():
    rows = []
    for fname in sorted(os.listdir(DIR)):
        if not fname.endswith(".json"):
            continue
        data = json.load(open(os.path.join(DIR, fname), encoding="utf8"))
        tool = data.get("components", {}).get("minecraft:tool")
        if tool is None:
            continue
        rules = []
        for r in tool.get("rules", []):
            b = r["blocks"]
            blocks = "|".join(b) if isinstance(b, list) else b
            rules.append((blocks, r.get("speed"), r.get("correct_for_drops")))
        rows.append((fname[:-5], float(tool.get("default_mining_speed", 1.0)), rules))

    dest = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "crates", "rewo-data", "src", "item_tools.rs",
    )
    out = open(dest, "w", encoding="utf8", newline="\n")
    out.write("//! GENERATED by `tools/gen_item_tools.py` — do not edit.\n")
    out.write(f"//!\n//! Source: the {VERSION} datagen item component reports' `minecraft:tool`.\n")
    out.write(f"//! {len(rows)} items carry one.\n\n")
    out.write("/// `(blocks, speed, correct_for_drops)`: `blocks` is `#tag`, an id, or ids\n")
    out.write("/// joined with `|`.\n")
    out.write("pub type ToolRule = (&'static str, Option<f32>, Option<bool>);\n\n")
    out.write("/// `(item, default_mining_speed, rules in order)`.\n")
    out.write("#[rustfmt::skip]\n")
    out.write("pub const ITEM_TOOLS: &[(&str, f32, &[ToolRule])] = &[\n")
    for name, default, rules in rows:
        parts = []
        for blocks, speed, correct in rules:
            sp = "None" if speed is None else f"Some({float(speed)!r})"
            co = "None" if correct is None else f"Some({str(correct).lower()})"
            parts.append(f'("{blocks}", {sp}, {co})')
        out.write(f'    ("minecraft:{name}", {default!r}, &[{", ".join(parts)}]),\n')
    out.write("];\n")
    out.close()
    print(f"[gen_item_tools] {len(rows)} items with a tool component")


if __name__ == "__main__":
    main()
