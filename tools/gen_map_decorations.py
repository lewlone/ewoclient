"""Generate crates/rewo-data/src/map_decoration_table.rs — map decoration types.

`MapDecorationTypes` registers each type as `register(name, assetName,
showOnItemFrame, ...)`; the sprite is `map/decorations/<assetName>` (NOT the
registry name: `mansion` draws `woodland_mansion`). The wire carries the type
as a raw `minecraft:map_decoration_type` registry id (`holderRegistry`), so the
table is ordered by the datagen report's `protocol_id`, and the generator
fails if a report entry has no Java constant or the ids are not dense.

Run:  python tools/gen_map_decorations.py
"""

from __future__ import annotations

import json
import os
import re
import sys

BASE = os.path.expandvars(r"%APPDATA%/EwoClient/rewo/26.2")
JAVA = os.path.join(BASE, "decompiled/net/minecraft/world/level/saveddata/maps/MapDecorationTypes.java")
REPORT = os.path.join(BASE, "datagen/generated/reports/registries.json")
OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "crates", "rewo-data", "src", "map_decoration_table.rs",
)


def die(msg: str) -> None:
    print(f"[gen_map_decorations] FAIL — {msg}")
    sys.exit(1)


def main() -> None:
    for p in (JAVA, REPORT):
        if not os.path.exists(p):
            die(f"missing {p}")
    java = open(JAVA, encoding="utf-8").read()
    # register("name", "asset", showOnItemFrame, ...) — possibly across lines.
    regs = {
        name: (asset, frame == "true")
        for name, asset, frame in re.findall(
            r'register\(\s*"([a-z_]+)",\s*"([a-z_]+)",\s*(true|false)', java, re.S
        )
    }
    if not regs:
        die("no register(...) calls found")
    report = json.load(open(REPORT, encoding="utf-8"))["minecraft:map_decoration_type"]["entries"]
    by_id = sorted(((v["protocol_id"], k.split(":", 1)[1]) for k, v in report.items()))
    if [i for i, _ in by_id] != list(range(len(by_id))):
        die("protocol ids are not dense")
    rows = []
    for i, name in by_id:
        if name not in regs:
            die(f"report entry {name} has no register(...) in MapDecorationTypes.java")
        asset, frame = regs[name]
        rows.append((name, asset, frame))
    out = [
        "//! Map decoration types by raw registry id — GENERATED by",
        "//! `tools/gen_map_decorations.py` from `MapDecorationTypes.java` and the",
        "//! datagen registry report. Do not edit; re-run after a version bump.",
        "",
        "/// `(registry name, sprite asset name, showOnItemFrame)`, indexed by the",
        "/// `minecraft:map_decoration_type` protocol id. The sprite is",
        "/// `textures/map/decorations/<asset>.png`.",
        f"pub const TYPES: [(&str, &str, bool); {len(rows)}] = [",
    ]
    out += [f'    ("{n}", "{a}", {"true" if f else "false"}),' for n, a, f in rows]
    out += ["];", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"[gen_map_decorations] wrote {OUT}: {len(rows)} types")


if __name__ == "__main__":
    main()
