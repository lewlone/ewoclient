"""Generate crates/rewo-data/src/map_colors.rs — vanilla's map palette (M190).

`MapColor` declares 62 materials as `new MapColor(id, rgb)` constants; a map
pixel is a packed byte `id << 2 | brightness`, and
`MapColor.getColorFromPackedId` turns it into ARGB with
`ARGB.scaleRGB(opaque(col), brightness.modifier)` — integer
`channel * modifier / 255` per channel — except for `NONE` (id 0), which is 0
(fully transparent). An id with no constant (62, 63) is `byIdUnsafe`'s `NONE`.

The four brightness modifiers are read from the `Brightness` enum
(`LOW(0, 180)`, `NORMAL(1, 220)`, `HIGH(2, 255)`, `LOWEST(3, 135)`) rather than
written here, so a version that retunes them regenerates rather than drifts.
The generator fails if the ids are not exactly `0..N` with no gaps or
repeats.

Run:  python tools/gen_map_colors.py
"""

from __future__ import annotations

import os
import re
import sys

VERSION = os.environ.get("REWO_VERSION", "26.2")
BASE = os.path.join(os.environ["APPDATA"], "EwoClient", "rewo", VERSION)
SRC = os.path.join(BASE, "decompiled/net/minecraft/world/level/material/MapColor.java")
OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "crates", "rewo-data", "src", "map_colors.rs",
)


def die(msg: str) -> None:
    print(f"[gen_map_colors] FAIL — {msg}")
    sys.exit(1)


def main() -> None:
    if not os.path.exists(SRC):
        die(f"no decompiled source at {SRC}")
    text = open(SRC, encoding="utf-8").read()
    colors = [
        (name, int(i), int(rgb))
        for name, i, rgb in re.findall(
            r"public static final MapColor (\w+) = new MapColor\((\d+), (-?\d+)\);", text
        )
    ]
    if not colors:
        die("no `new MapColor(id, rgb)` constants found")
    ids = [i for _, i, _ in colors]
    if ids != list(range(len(ids))):
        die(f"ids are not 0..{len(ids) - 1} in order: {ids}")
    bright = re.findall(r"\b(LOW|NORMAL|HIGH|LOWEST)\((\d), (\d+)\)", text)
    if [b[0] for b in bright] != ["LOW", "NORMAL", "HIGH", "LOWEST"] or [
        int(b[1]) for b in bright
    ] != [0, 1, 2, 3]:
        die(f"unexpected Brightness enum: {bright}")
    mods = [int(b[2]) for b in bright]

    out = []
    out.append("//! Vanilla's map palette — GENERATED by `tools/gen_map_colors.py` from")
    out.append("//! `MapColor.java`. Do not edit; re-run after a version bump.")
    out.append("//!")
    out.append("//! A map pixel is a packed byte `id << 2 | brightness`; see")
    out.append("//! [`argb_from_packed`] for `MapColor.getColorFromPackedId`.")
    out.append("")
    out.append("/// `MapColor.MATERIAL_COLORS` that are declared, as `(name, rgb)` by id.")
    out.append(f"pub const MATERIALS: [(&str, u32); {len(colors)}] = [")
    for name, _, rgb in colors:
        out.append(f"    (\"{name}\", 0x{rgb & 0xFFFFFF:06X}),")
    out.append("];")
    out.append("")
    out.append("/// `MapColor.Brightness` modifiers, by brightness id: LOW, NORMAL, HIGH, LOWEST.")
    out.append(f"pub const BRIGHTNESS: [u32; 4] = [{', '.join(str(m) for m in mods)}];")
    out.append("")
    out.append("/// `MapColor.getColorFromPackedId(packed)` as `0xAARRGGBB`.")
    out.append("///")
    out.append("/// `NONE` (id 0) and an undeclared id are 0, fully transparent; every other")
    out.append("/// colour is opaque with each channel `channel * modifier / 255` in integers")
    out.append("/// (`ARGB.scaleRGB(int, int)`).")
    out.append("pub fn argb_from_packed(packed: u8) -> u32 {")
    out.append("    let id = (packed >> 2) as usize;")
    out.append("    let Some(&(_, rgb)) = MATERIALS.get(id) else {")
    out.append("        return 0;")
    out.append("    };")
    out.append("    if id == 0 {")
    out.append("        return 0;")
    out.append("    }")
    out.append("    let m = BRIGHTNESS[(packed & 3) as usize];")
    out.append("    let ch = |shift: u32| ((rgb >> shift) & 0xFF) * m / 255;")
    out.append("    0xFF00_0000 | ch(16) << 16 | ch(8) << 8 | ch(0)")
    out.append("}")
    out.append("")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"[gen_map_colors] wrote {OUT}: {len(colors)} materials, brightness {mods}")


if __name__ == "__main__":
    main()
