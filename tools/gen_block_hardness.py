"""Extract every block's destroy time and `requiresCorrectToolForDrops` from
the decompiled `Blocks.java` into `crates/rewo-data/src/block_hardness.rs`
(M217, survival block breaking).

Neither fact is in a datagen report: both are `BlockBehaviour.Properties`
builder calls in code.

* `.strength(d, r)` and `.strength(d)` set `destroyTime = d`; `.instabreak()`
  is `strength(0.0F)`; `.destroyTime(d)` sets it directly. The field defaults
  to 0 (`private float destroyTime;`), and -1 means unbreakable (bedrock).
* `.requiresCorrectToolForDrops()` sets the flag; it defaults to false.
* `Properties.ofLegacyCopy(FIELD)` / `ofFullCopy(FIELD)` copy both from the
  named block (`copyTo.destroyTime = copyFrom.destroyTime;`
  `copyTo.requiresCorrectToolForDrops = ...`), so a block that sets neither
  inherits them; the copying block's own calls win.

Precedence per block: the registration's own builder chain (the last matching
call in it, which is what runs last), then the `Properties` helpers it calls
(`logProperties(...)` and friends, inlined by `gen_block_light`'s walker),
then the copied block, then the default.

Reuses `gen_block_light.py`'s registration walker, so the two tables agree on
which registry names exist. Re-run after a version bump.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_block_light as gbl  # noqa: E402

FLOAT = r"(-?\d+(?:\.\d+)?)[Ff]?"
CALLS = re.compile(
    r"\.(strength|instabreak|destroyTime)\s*\(\s*(?:" + FLOAT + r")?"
)


def destroy_time(text):
    """The destroy time the LAST builder call in `text` sets, or None."""
    found = None
    for m in CALLS.finditer(text):
        kind, value = m.group(1), m.group(2)
        if kind == "instabreak":
            found = 0.0
        elif value is not None:
            found = float(value)
    return found


def main():
    src = open(gbl.BLOCKS, encoding="utf8", errors="replace").read()
    known = set(json.load(open(gbl.REGISTRY, encoding="utf8")).keys())
    helpers = gbl.property_helpers(src)
    regs = list(gbl.iter_registrations(src, helpers))
    by_field = {field: parts for field, _n, parts, _c, idx in regs if idx is None}

    def resolve(parts, depth=0):
        own = parts[0]
        helper_text = "\n".join(parts[1:])
        t = destroy_time(own)
        if t is None:
            t = destroy_time(helper_text)
        req = ".requiresCorrectToolForDrops()" in own or ".requiresCorrectToolForDrops()" in helper_text
        m = re.search(r"of(?:Legacy|Full)Copy\(\s*([A-Z0-9_]+)\s*\)", own)
        if m and depth < 8 and m.group(1) in by_field:
            ct, creq = resolve(by_field[m.group(1)], depth + 1)
            if t is None:
                t = ct
            req = req or creq
        return t, req

    rows = {}
    for _field, name, parts, _cls, _idx in regs:
        if f"minecraft:{name}" not in known:
            continue
        t, req = resolve(parts)
        rows[name] = (0.0 if t is None else t, req)

    missing = sorted(n.split(":", 1)[1] for n in known if n.split(":", 1)[1] not in rows)
    dest = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "crates", "rewo-data", "src", "block_hardness.rs",
    )
    out = open(dest, "w", encoding="utf8", newline="\n")
    out.write("//! GENERATED by `tools/gen_block_hardness.py` — do not edit.\n")
    out.write(f"//!\n//! Source: decompiled {gbl.VERSION} `Blocks.java`. Every registered block's\n")
    out.write("//! `destroyTime` (-1 = unbreakable) and `requiresCorrectToolForDrops`.\n")
    out.write(f"//! {len(rows)} blocks; {len(missing)} registry names not found by the walker.\n\n")
    out.write("/// `(block, destroyTime, requiresCorrectToolForDrops)`.\n")
    out.write("#[rustfmt::skip]\n")
    out.write("pub const BLOCK_HARDNESS: &[(&str, f32, bool)] = &[\n")
    for k in sorted(rows):
        t, req = rows[k]
        out.write(f'    ("minecraft:{k}", {t!r}, {str(req).lower()}),\n')
    out.write("];\n")
    out.close()
    print(f"[gen_block_hardness] {len(rows)} blocks, {len(missing)} missing: {missing[:8]}")


if __name__ == "__main__":
    main()
